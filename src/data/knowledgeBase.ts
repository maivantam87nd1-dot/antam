// Semantic keyword & token retrieval engine for RAG
export function retrieveKnowledgeChunks(query: string, maxResults = 3): KnowledgeChunk[] {
  if (!query || !query.trim()) return VERIFIED_KNOWLEDGE_BASE.slice(0, maxResults);

  const normalized = query.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  const rawWords = query.toLowerCase().split(/\s+/).filter(w => w.length > 1);

  const scored = VERIFIED_KNOWLEDGE_BASE.map(chunk => {
    let score = 0;
    const chunkTitle = chunk.documentTitle.toLowerCase();
    const chunkChapter = (chunk.chapter || '').toLowerCase();
    const chunkContent = chunk.content.toLowerCase();
    const chunkKeywords = chunk.keywords.map(k => k.toLowerCase());

    // Keyword exact check
    chunkKeywords.forEach(k => {
      if (normalized.includes(k) || query.toLowerCase().includes(k)) {
        score += 15;
      }
    });

    // Title / Chapter match
    rawWords.forEach(word => {
      if (chunkTitle.includes(word)) score += 8;
      if (chunkChapter.includes(word)) score += 6;
      if (chunkContent.includes(word)) score += 2;
    });

    return { chunk, score };
  });

  scored.sort((a, b) => b.score - a.score);
  const relevant = scored.filter(s => s.score > 0).map(s => s.chunk);

  if (relevant.length === 0) {
    // Return standard foundation texts if no specific topic was matched
    return VERIFIED_KNOWLEDGE_BASE.slice(0, maxResults);
  }

  return relevant.slice(0, maxResults);
}
